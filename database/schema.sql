-- 16. Domain Audit Logs Table
CREATE TABLE IF NOT EXISTS domain_audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_id   BIGINT REFERENCES domains(id) ON DELETE CASCADE,
