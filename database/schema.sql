-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT DEFAULT 'viewer',
  avatar_color TEXT DEFAULT '#6366f1',
  avatar_seed TEXT DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_login TIMESTAMPTZ,
  session_token TEXT DEFAULT NULL
);


-- 2. Websites Table
CREATE TABLE IF NOT EXISTS websites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  name TEXT NOT NULL,
  domain TEXT NOT NULL,
  api_key TEXT UNIQUE NOT NULL,
  demo_slug TEXT UNIQUE,
  logo_url TEXT DEFAULT NULL,
  color TEXT DEFAULT '#6366f1',
  is_active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  -- Domain routing
  domain_active INTEGER DEFAULT 1,
  domain_alt TEXT DEFAULT NULL,
  domain_alt_active INTEGER DEFAULT 0,
  -- Per-website Telegram bot
  tg_bot_token TEXT DEFAULT NULL,
  tg_chat_id TEXT DEFAULT NULL,
  tg_allowed_users TEXT DEFAULT '[]',
  tg_bot_active INTEGER DEFAULT 0
);

-- 3. Sessions Table
CREATE TABLE IF NOT EXISTS sessions (
  id TEXT PRIMARY KEY,
  website_id BIGINT REFERENCES websites(id) ON DELETE SET NULL,
  visitor_id TEXT,
  ip_address TEXT,
  user_agent TEXT,
  browser TEXT,
  os TEXT,
  device TEXT,
  country TEXT,
  city TEXT,
  current_page TEXT,
  referrer TEXT,
  pages_viewed INTEGER DEFAULT 1,
  started_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_activity TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  is_active INTEGER DEFAULT 1,
  metadata TEXT DEFAULT '{}'
);

-- 4. Page Views Table
CREATE TABLE IF NOT EXISTS page_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT REFERENCES sessions(id) ON DELETE CASCADE,
  website_id BIGINT REFERENCES websites(id) ON DELETE CASCADE,
  page_url TEXT,
  page_title TEXT,
  duration_ms INTEGER DEFAULT 0,
  timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. Redirect Rules Table
CREATE TABLE IF NOT EXISTS redirect_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  website_id BIGINT REFERENCES websites(id) ON DELETE CASCADE,
  name TEXT,
  source_pattern TEXT DEFAULT '*',
  target_url TEXT NOT NULL,
  is_active INTEGER DEFAULT 1,
  apply_when_offline INTEGER DEFAULT 0,
  priority INTEGER DEFAULT 0,
  conditions TEXT DEFAULT '{}',
  redirect_count INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. Redirect Commands Table
CREATE TABLE IF NOT EXISTS redirect_commands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT,
  website_id BIGINT,
  target_url TEXT,
  executed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  executed_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);

-- 7. Notifications Table
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  type TEXT DEFAULT 'info',
  title TEXT,
  message TEXT,
  link TEXT,
  is_read INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. Audit Logs Table
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  username TEXT,
  action TEXT,
  category TEXT DEFAULT 'general',
  details TEXT DEFAULT '{}',
  ip_address TEXT,
  timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 9. Settings Table
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 10. Telegram Config Table
CREATE TABLE IF NOT EXISTS telegram_config (
  id BIGINT PRIMARY KEY DEFAULT 1,
  bot_token TEXT DEFAULT '',
  chat_id TEXT DEFAULT '',
  is_active INTEGER DEFAULT 0,
  notify_new_session INTEGER DEFAULT 1,
  notify_form_data INTEGER DEFAULT 1,
  notify_errors INTEGER DEFAULT 1,
  notify_page_views INTEGER DEFAULT 0
);

-- 11. Blocked IPs Table
CREATE TABLE IF NOT EXISTS blocked_ips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  ip_address TEXT NOT NULL,
  type TEXT DEFAULT 'manual',
  reason TEXT DEFAULT '',
  expires_at TIMESTAMPTZ DEFAULT NULL,
  blocked_requests INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (owner_id, ip_address)
);

-- 12. Activity Feed Table
CREATE TABLE IF NOT EXISTS activity_feed (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  type TEXT,
  icon TEXT,
  message TEXT,
  details TEXT DEFAULT '{}',
  website_id BIGINT,
  session_id TEXT,
  timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
